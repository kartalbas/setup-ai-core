# The map of a repository, generated from its code: repos\<repo>\AGENTS.md of the project
# harness, which init lays into the checkout as AGENTS.md, the file every agent reads first.
# Five fixed sections, at most 80 lines, written by the developer's agent CLI; the section
# "Rules of this repository" is written by people and kept through every regeneration.
#
#   map.ps1 [-TargetDir <path>] [-All <folder>] [-NoPush] [-DryRun]
#
[CmdletBinding()]
param (
  [switch]$Help,
  [string]$TargetDir = ".",
  [string]$All = "",
  [switch]$NoPush,
  [switch]$DryRun
)

if ($Help -or $args -ccontains "-h" -or $args -ccontains "--help" -or $TargetDir -ceq "--help" -or $TargetDir -ceq "-h") {
  Write-Host "Usage: map.ps1 [-TargetDir <path>] [-All <folder>] [-NoPush] [-DryRun]"
  Write-Host ""
  Write-Host "Generates the map of the repository in TargetDir (default: the current directory) from its"
  Write-Host "code, with the agent CLI named by MAP_TOOL in .ai-core\config.env (claude), into"
  Write-Host "repos\<repo>\AGENTS.md of the project harness: what it is, its shape, how it is built,"
  Write-Host "checked and run, where things are added, and the rules of this repository, which people"
  Write-Host "write and every regeneration keeps. At most 80 lines. Then the harness is committed and"
  Write-Host "pushed and the checkout assembled again, so the map is in place at once."
  Write-Host ""
  Write-Host "Options:"
  Write-Host "  -TargetDir <path>   Target directory (default: current)"
  Write-Host "  -All <folder>       The map of every repository directly under the folder, one push, then init -All"
  Write-Host "  -NoPush             Write the map into the harness clone and stop: no commit, no push, no init"
  Write-Host "  -DryRun             Print the map that would be written; write nothing"
  Write-Host "  -Help               Show this help message"
  Write-Host ""
  Write-Host "Examples:"
  Write-Host "  ai-core map"
  Write-Host "  ai-core map -All ../my-org"
  exit 0
}

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [Text.Encoding]::UTF8
$core = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Import-Module (Join-Path $core 'lib\Layers.psm1') -Force

# -All: every repository directly under the folder, the harness clones excepted; one push at
# the end and init -All, so every checkout carries its map
if ($All) {
  $allDir = (Resolve-Path $All).Path
  $ok = 0; $failed = @()
  $pass = @('-NoPush'); if ($DryRun) { $pass += '-DryRun' }
  foreach ($repo in Get-ChildItem -Path $allDir -Directory | Where-Object { $_.Name -cnotlike '*-ai-core' -and (Test-Path (Join-Path $_.FullName ".git")) }) {
    Write-Host ""; Write-Host "### $($repo.Name)"
    & pwsh -NoProfile -File $MyInvocation.MyCommand.Path -TargetDir $repo.FullName @pass
    if ($LASTEXITCODE -eq 0) { $ok++ } else { $failed += $repo.Name }
  }
  Write-Host ""; Write-Host "==> map -All: $ok map(s) $(if ($DryRun) { 'would be' } else { 'were' }) written$(if ($failed) { '; failed: ' + ($failed -join ' ') })"
  if (-not $DryRun -and -not $NoPush -and $ok -gt 0) {
    Push-Location $allDir
    try { & pwsh -NoProfile -File (Join-Path $core 'bin\push.ps1') "the maps of $ok repositories, generated by ai-core map" } finally { Pop-Location }
    & pwsh -NoProfile -File (Join-Path $core 'bin\init.ps1') -All $allDir -NoDoctor
  }
  if ($failed) { exit 1 } else { exit 0 }
}

$target = (Resolve-Path $TargetDir).Path
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("ai-core-map-" + [System.IO.Path]::GetRandomFileName())
New-Item -ItemType Directory -Force -Path $tmp | Out-Null
$utf8 = New-Object System.Text.UTF8Encoding $false
function Stop-Map([string]$message) { Write-Host "error: $message" -ForegroundColor Red; Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue; exit 1 }

# 1. The repository, its harness and the innermost layer, where the map lives
$parts = Get-OriginParts $target
if (-not $parts) { Stop-Map "$target has no origin on github.com; a map lives in the project harness" }
$org = $parts[0]; $repo = $parts[1]
$prefix = Get-HarnessOf $repo
if (-not $prefix) { Stop-Map "$repo is setup-ai-core or a harness; map is for the repositories a harness serves" }
try { $layers = @(Resolve-LayerChain -Full "$org/$prefix-ai-core" -Root $core -Folder (Get-ProjectFolderOf $target)) } catch { Stop-Map $_.Exception.Message }
$inner = $layers[-1]
$map = Join-Path $inner "repos\$repo\AGENTS.md"

# 2. The agent CLI, from the checkout's configuration
$config = Join-Path $target '.ai-core\config.env'; if (-not (Test-Path $config)) { $config = Join-Path $core 'templates\.ai-core\config.env' }
function Get-Setting([string]$key) {
  $l = Get-Content $config | Where-Object { $_ -cmatch "^\s*$key\s*=" } | Select-Object -Last 1
  if ($l) { return ((($l -split '=', 2)[1] -split '#', 2)[0]).Trim(' ', "`t", "`r", '"', "'") } else { return '' }
}
$tool = Get-Setting 'MAP_TOOL'; if (-not $tool) { $tool = 'claude' }
$model = Get-Setting 'MAP_MODEL'
if ($tool -cne 'claude') { Stop-Map "MAP_TOOL=`"$tool`" in $config; claude is the tool map runs with today" }
if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) { Stop-Map "$tool is not on the PATH; map writes the map with it" }

# 3. The prompt: read cheaply, output only the file, in the fixed shape. The last section is
#    people's and comes back from the map that exists.
$prompt = @"
Write the map of this repository: the file AGENTS.md that every coding agent reads first.
Read the repository first, cheaply: run ``graft map`` and ``graft skeleton`` on the entry points when ``graft`` is on the PATH; read the manifests (package.json, pubspec.yaml, pyproject.toml, go.mod, Cargo.toml, Makefile, the scripts/ folder, the CI workflows) and the README. Do not read every source file.
Then output ONLY the finished file, nothing before it and nothing after it, in English, at most 80 lines, in exactly this shape:

# $repo — the map

## What it is
Three sentences: what it is for, who uses it, what it is not.

## Shape
One line per top-level directory that matters, and the entry points, with their paths.

## Build, check, run
The exact commands, one per line, as the manifests and the CI define them.

## Where to add things
A table with two columns: what is added, and where it goes and where it is registered, from the code's own conventions.

## Rules of this repository
(none yet: written by people, kept on every regeneration)

Keep every heading exactly as given, in this order. Write paths as they are in the repository. Leave the last section exactly as given. No introduction, no closing remark, no code fence around the file.
"@

Write-Host "--> Map of $repo, written by $tool$(if ($model) { " ($model)" }) into $map"
$cliArgs = @('-p', $prompt, '--output-format', 'text'); if ($model) { $cliArgs += @('--model', $model) }
$cliArgs += @('--allowedTools', 'Read,Glob,Grep,Bash(graft:*),Bash(npx:*)')
$errFile = Join-Path $tmp 'map.err'
Push-Location $target
try { $raw = @(& $tool @cliArgs 2>$errFile | ForEach-Object { "$_" }); $code = $LASTEXITCODE } finally { Pop-Location }
if ($code -ne 0) {
  $tail = if (Test-Path $errFile) { @(Get-Content $errFile | Select-Object -Last 5) -join "`n" } else { '' }
  Stop-Map "$tool did not write the map (exit $code):`n$tail"
}

# 4. The shape is checked before anything is written: the title line, the five headings in
#    order, the length. A fence the tool put around the file is dropped; blank edges are cut.
$lines = @($raw | ForEach-Object { $_.TrimEnd("`r") } | Where-Object { -not $_.StartsWith('```', [StringComparison]::Ordinal) })
while ($lines.Count -gt 0 -and -not $lines[0].Trim()) { $lines = $lines[1..($lines.Count - 1)] }
while ($lines.Count -gt 0 -and -not $lines[-1].Trim()) { $lines = @($lines[0..($lines.Count - 2)]) }
$headings = @($lines | Where-Object { $_.StartsWith('## ', [StringComparison]::Ordinal) }) -join '|'
$wanted = '## What it is|## Shape|## Build, check, run|## Where to add things|## Rules of this repository'
if ($lines.Count -eq 0 -or $lines[0] -cne "# $repo — the map" -or $headings -cne $wanted -or $lines.Count -gt 80) {
  New-Item -ItemType Directory -Force -Path (Join-Path $target '.ai-core') | Out-Null
  [System.IO.File]::WriteAllText((Join-Path $target '.ai-core\map.rejected.md'), (($raw -join "`n") + "`n"), $utf8)
  Stop-Map "what $tool wrote is not the map's shape (the title '# $repo — the map', the five headings in order, at most 80 lines); kept for a look at $target\.ai-core\map.rejected.md, nothing written"
}
if (Test-Path -LiteralPath $map) {
  $old = @([System.IO.File]::ReadAllLines($map) | ForEach-Object { $_.TrimEnd("`r") })
  $at = [Array]::FindIndex($old, [Predicate[string]]{ param($l) $l.StartsWith('## Rules of this repository', [StringComparison]::Ordinal) })
  if ($at -ge 0) {
    $kept = @($old[$at..($old.Count - 1)])
    $cut = [Array]::FindIndex($lines, [Predicate[string]]{ param($l) $l.StartsWith('## Rules of this repository', [StringComparison]::Ordinal) })
    $lines = @($lines[0..($cut - 1)]) + $kept
  }
}
$commit = "$(& git -C $target rev-parse --short HEAD 2>$null)".Trim()
$final = @("<!-- ai-core map: generated $(Get-Date -Format 'yyyy-MM-dd') from $commit; the section `"Rules of this repository`" is written by people and kept -->") + $lines
$text = ($final -join "`n") + "`n"

if ($DryRun) {
  Write-Host "--> Dry run: the map that would be written into $map"; Write-Host ""; Write-Host $text.TrimEnd("`n")
  Remove-Item -LiteralPath $tmp -Recurse -Force; exit 0
}

# 5. Into the harness, committed and pushed, and the checkout assembled again
if (Test-Path -LiteralPath $map) {
  $oldBody = @([System.IO.File]::ReadAllLines($map) | ForEach-Object { $_.TrimEnd("`r") } | Select-Object -Skip 1) -join "`n"
  if ($oldBody -ceq (($lines -join "`n"))) { Write-Host "--> Map unchanged: $map"; Remove-Item -LiteralPath $tmp -Recurse -Force; exit 0 }
}
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $map) | Out-Null
[System.IO.File]::WriteAllText($map, $text, $utf8)
Write-Host "--> Map written: $map ($($final.Count) lines)"
Remove-Item -LiteralPath $tmp -Recurse -Force
if ($NoPush) { exit 0 }
Push-Location $target
try { & pwsh -NoProfile -File (Join-Path $core 'bin\push.ps1') "map: $repo, generated by ai-core map"; exit $LASTEXITCODE } finally { Pop-Location }
