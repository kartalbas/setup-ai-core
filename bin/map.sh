#!/usr/bin/env bash
# The map of a repository, generated from its code: repos/<repo>/AGENTS.md of the project
# harness, which init lays into the checkout as AGENTS.md, the file every agent reads first.
# Five fixed sections, at most 80 lines, written by the developer's agent CLI; the section
# "Rules of this repository" is written by people and kept through every regeneration.
#
#   map.sh [TARGET_DIR] [--all <folder>] [--no-push] [--dry-run]
#
set -euo pipefail

for arg in "$@"; do
  if [[ "$arg" == "-h" || "$arg" == "--help" ]]; then
    echo "Usage: map.sh [TARGET_DIR] [--all <folder>] [--no-push] [--dry-run]"
    echo ""
    echo "Generates the map of the repository in TARGET_DIR (default: the current directory) from its"
    echo "code, with the agent CLI named by MAP_TOOL in .ai-core/config.env (claude), into"
    echo "repos/<repo>/AGENTS.md of the project harness: what it is, its shape, how it is built,"
    echo "checked and run, where things are added, and the rules of this repository, which people"
    echo "write and every regeneration keeps. At most 80 lines. Then the harness is committed and"
    echo "pushed and the checkout assembled again, so the map is in place at once."
    echo ""
    echo "Options:"
    echo "  -h, --help       Show this help message"
    echo "  --all <folder>   The map of every repository directly under the folder, one push, then init --all"
    echo "  --no-push        Write the map into the harness clone and stop: no commit, no push, no init"
    echo "  --dry-run        Print the map that would be written; write nothing"
    echo ""
    echo "Examples:"
    echo "  ai-core map"
    echo "  ai-core map --all ../my-org"
    exit 0
  fi
done

CORE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
. "$CORE/lib/layers.sh"

TARGET="."; ALL_DIR=""; PUSH=1; DRY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --all) shift; [ $# -gt 0 ] || { echo "error: --all needs a folder" >&2; exit 1; }; ALL_DIR="$1" ;;
    --no-push) PUSH=0 ;;
    --dry-run) DRY=1 ;;
    -*) echo "error: unknown option '$1' (see --help)" >&2; exit 1 ;;
    *) TARGET="$1" ;;
  esac
  shift
done

# --all: every repository directly under the folder, the harness clones excepted; one push at
# the end and init --all, so every checkout carries its map
if [ -n "$ALL_DIR" ]; then
  ALL_DIR="$(cd "$ALL_DIR" && pwd)"
  OK=0; FAILED=""
  PASS=(--no-push); [ "$DRY" -eq 1 ] && PASS+=(--dry-run)
  for repo in "$ALL_DIR"/*/; do
    repo="${repo%/}"
    [ -e "$repo/.git" ] || continue
    case "$(basename "$repo")" in *-ai-core) continue ;; esac
    echo ""; echo "### $(basename "$repo")"
    if bash "${BASH_SOURCE[0]}" "$repo" "${PASS[@]}"; then OK=$((OK + 1)); else FAILED="$FAILED $(basename "$repo")"; fi
  done
  echo ""; echo "==> map --all: $OK map(s) $([ "$DRY" -eq 1 ] && echo "would be" || echo "were") written${FAILED:+; failed:$FAILED}"
  if [ "$DRY" -eq 0 ] && [ "$PUSH" -eq 1 ] && [ "$OK" -gt 0 ]; then
    (cd "$ALL_DIR" && bash "$CORE/bin/push.sh" "the maps of $OK repositories, generated by ai-core map")
    bash "$CORE/bin/init.sh" --all "$ALL_DIR" --no-doctor
  fi
  [ -z "$FAILED" ]
  exit $?
fi

TARGET="$(cd "$TARGET" && pwd)"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

# 1. The repository, its harness and the innermost layer, where the map lives
parts="$(origin_parts "$TARGET")" || { echo "error: $TARGET has no origin on github.com; a map lives in the project harness" >&2; exit 1; }
org="${parts%%	*}"; repo="${parts#*	}"
prefix="$(harness_of "$repo")" || { echo "error: $repo is setup-ai-core or a harness; map is for the repositories a harness serves" >&2; exit 1; }
LAYERS="$(layer_chain "$org/$prefix-ai-core" "$CORE" "$(project_folder_of "$TARGET")")" || exit 1
INNER="$(printf '%s\n' "$LAYERS" | tail -n1)"
MAP="$INNER/repos/$repo/AGENTS.md"

# 2. The agent CLI, from the checkout's configuration
CONFIG="$TARGET/.ai-core/config.env"; [ -f "$CONFIG" ] || CONFIG="$CORE/templates/.ai-core/config.env"
setting() { { grep -E "^[[:space:]]*$1[[:space:]]*=" "$CONFIG" || true; } | tail -n1 | sed 's/^[^=]*=//; s/#.*//' | tr -d '"\r' | tr -d "'" | sed 's/^ *//; s/ *$//'; }
TOOL="$(setting MAP_TOOL)"; [ -n "$TOOL" ] || TOOL=claude
MODEL="$(setting MAP_MODEL)"
case "$TOOL" in
  claude) ;;
  *) echo "error: MAP_TOOL=\"$TOOL\" in $CONFIG; claude is the tool map runs with today" >&2; exit 1 ;;
esac
command -v "$TOOL" >/dev/null 2>&1 || { echo "error: $TOOL is not on the PATH; map writes the map with it" >&2; exit 1; }

# 3. The prompt: read cheaply, output only the file, in the fixed shape. The last section is
#    people's and comes back from the map that exists.
PROMPT="Write the map of this repository: the file AGENTS.md that every coding agent reads first.
Read the repository first, cheaply: run \`graft map\` and \`graft skeleton\` on the entry points when \`graft\` is on the PATH; read the manifests (package.json, pubspec.yaml, pyproject.toml, go.mod, Cargo.toml, Makefile, the scripts/ folder, the CI workflows) and the README. Do not read every source file.
Then output ONLY the finished file, nothing before it and nothing after it, in English, at most 80 lines, in exactly this shape:

# $repo — the map

## What it is
Three sentences: what it is for, who uses it, what it is not.

## Shape
One line per top-level directory that matters, and the entry points, with their paths.

## Build, check, run
The exact commands, one per line, as the manifests and the CI define them.

## Where to add things
A table with two columns: what is added, and where it goes and where it is registered, from the code's own conventions.

## Rules of this repository
(none yet: written by people, kept on every regeneration)

Keep every heading exactly as given, in this order. Write paths as they are in the repository. Leave the last section exactly as given. No introduction, no closing remark, no code fence around the file."

echo "--> Map of $repo, written by $TOOL${MODEL:+ ($MODEL)} into $MAP"
RAW="$TMP/map.raw"; ERR="$TMP/map.err"
if ! (cd "$TARGET" && "$TOOL" -p "$PROMPT" --output-format text ${MODEL:+--model "$MODEL"} --allowedTools "Read,Glob,Grep,Bash(graft:*),Bash(npx:*)") > "$RAW" 2>"$ERR"; then
  echo "error: $TOOL did not write the map (exit $?):" >&2; tail -n 5 "$ERR" >&2; exit 1
fi

# 4. The shape is checked before anything is written: the title line, the five headings in
#    order, the length. A fence the tool put around the file is dropped; blank edges are cut.
tr -d '\r' < "$RAW" | sed '/^```/d' | awk 'NF{f=1} f' | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' > "$TMP/map.md"
shape_ok() {
  [ "$(head -n1 "$TMP/map.md")" = "# $repo — the map" ] || return 1
  [ "$(grep '^## ' "$TMP/map.md" | tr '\n' '|')" = "## What it is|## Shape|## Build, check, run|## Where to add things|## Rules of this repository|" ] || return 1
  [ "$(wc -l < "$TMP/map.md" | tr -d ' ')" -le 80 ]
}
if ! shape_ok; then
  mkdir -p "$TARGET/.ai-core"; cp "$RAW" "$TARGET/.ai-core/map.rejected.md"
  echo "error: what $TOOL wrote is not the map's shape (the title '# $repo — the map', the five headings in order, at most 80 lines); kept for a look at $TARGET/.ai-core/map.rejected.md, nothing written" >&2
  exit 1
fi
if [ -f "$MAP" ]; then
  KEPT="$(tr -d '\r' < "$MAP" | awk '/^## Rules of this repository/{f=1} f')"
  if [ -n "$KEPT" ]; then
    awk '/^## Rules of this repository/{exit} {print}' "$TMP/map.md" > "$TMP/map.new"
    printf '%s\n' "$KEPT" >> "$TMP/map.new"; mv "$TMP/map.new" "$TMP/map.md"
  fi
fi
{
  printf '<!-- ai-core map: generated %s from %s; the section "Rules of this repository" is written by people and kept -->\n' "$(date +%Y-%m-%d)" "$(git -C "$TARGET" rev-parse --short HEAD)"
  cat "$TMP/map.md"
} > "$TMP/map.final"

if [ "$DRY" -eq 1 ]; then
  echo "--> Dry run: the map that would be written into $MAP"; echo ""; cat "$TMP/map.final"; exit 0
fi

# 5. Into the harness, committed and pushed, and the checkout assembled again
if [ -f "$MAP" ] && [ "$(tail -n +2 "$MAP" | tr -d '\r')" = "$(tail -n +2 "$TMP/map.final")" ]; then
  echo "--> Map unchanged: $MAP"
  exit 0
fi
mkdir -p "$(dirname "$MAP")"; cp "$TMP/map.final" "$MAP"
echo "--> Map written: $MAP ($(wc -l < "$MAP" | tr -d ' ') lines)"
[ "$PUSH" -eq 1 ] || exit 0
(cd "$TARGET" && bash "$CORE/bin/push.sh" "map: $repo, generated by ai-core map")
